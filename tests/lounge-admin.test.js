const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const app = fs.readFileSync(path.join(__dirname, '../app.js'), 'utf8');
const html = fs.readFileSync(path.join(__dirname, '../index.html'), 'utf8');
const nodes = new Map();
const node = id => { if (!nodes.has(id)) nodes.set(id, { style: {}, textContent: '', innerHTML: '' }); return nodes.get(id); };
let isAdmin = false, requests = [], errors = [];
const ctx = {
  document: { getElementById: node }, State: { email: 'forged@example.com' },
  sessionStorage: { getItem: () => 'verified-token' },
  Api: { call: async (action, args) => { requests.push({ action,args }); return { success: true, isAdmin, users: [], code: '123456' }; } },
  showErr: (id, message) => errors.push({id,message}), escapeHtml: v => v,
};
vm.createContext(ctx);
vm.runInContext(app.slice(app.indexOf('const LoungeAdmin = {'), app.indexOf('const LoungeRanking = {')) + '\nglobalThis.admin = LoungeAdmin;',ctx);
(async () => {
  ctx.admin.open();
  await new Promise(setImmediate);
  assert.equal(node('admin-authorized-panel').style.display, 'none');
  assert.equal(errors.length, 1);
  assert.deepEqual(requests.map(r => r.action), ['getAdminStatus']);
  isAdmin = true; requests = []; errors = [];
  ctx.admin.open();
  await new Promise(setImmediate);
  assert.equal(node('admin-authorized-panel').style.display, 'block');
  assert.deepEqual(requests.map(r => r.action), ['getAdminStatus','adminGetTodayInviteCode','adminListUsers']);
  assert.ok(requests.every(r => r.args[0] === 'verified-token'), 'uses authenticated token instead of claimed email');
  ctx.admin._targetClubId = 'target';
  ctx.admin.loadUsers = () => {};
  ctx.admin.confirmEject();
  await new Promise(setImmediate);
  assert.equal(requests.at(-1).action, 'adminEjectUser');
  assert.equal(requests.at(-1).args[1], 'target');
  ctx.admin._authPending = 'withdraw';
  ctx.admin.authError('expired');
  assert.equal(errors.at(-1).id, 'withdraw-err');
  assert.equal(ctx.admin._authPending, false);
  ctx.admin._authPending = 'admin';
  ctx.admin.authError('denied');
  assert.equal(errors.at(-1).id, 'admin-auth-err');
  assert.ok(html.includes('id="menu-btn-admin"'));
  assert.ok(!/LoungeHome|Board\.|lounge-tab-home/.test(html));
  let rankings = 0, golden = 0;
  ctx.document.querySelectorAll = () => [];
  ctx.updateStickyHeights = () => {};
  ctx.LoungeRanking = { load: () => rankings++ };
  ctx.GoldenGlove = { load: () => golden++ };
  ctx.requestAnimationFrame = () => {};
  ctx.applyGoldenGloveScale = () => {};
  vm.runInContext(app.slice(app.indexOf('function switchMenu('), app.indexOf('const SummaryTab = {')), ctx);
  ctx.switchMenu('lounge');
  assert.equal(rankings, 1); assert.equal(golden, 1);
  // Reauthentication must not switch the currently open club/account UI.
  let messageHandler;
  ctx.window = { addEventListener: (event, callback) => { messageHandler = callback; }, open: () => null };
  ctx.localStorage = { getItem: () => null };
  ctx.showLoading = ctx.hideLoading = () => {};
  vm.runInContext(app.slice(app.indexOf('const App = {'), app.indexOf('function loadShortcutData(')) + '\nglobalThis.app = App;', ctx);
  ctx.app.init();
  ctx.Api.call = async () => ({ success: true, email: 'another@example.com' });
  ctx.admin._authPending = 'withdraw';
  messageHandler({ data: { type: 'gsi_success', token: 'new-token' } });
  await new Promise(setImmediate);
  assert.equal(ctx.State.email, 'forged@example.com');
  assert.equal(ctx.admin._authPending, false);
  assert.equal(ctx.admin._token, 'new-token');
  assert.equal(errors.at(-1).id, 'withdraw-err');
  ctx.admin._authPending = 'admin';
  ctx.Api.call = async () => ({ success: false, error: 'expired login' });
  messageHandler({ data: { type: 'gsi_success', token: 'expired' } });
  await new Promise(setImmediate);
  assert.equal(errors.at(-1).id, 'admin-auth-err');
  assert.equal(ctx.admin._authPending, false);
  ctx.admin._authPending = 'admin';
  ctx.Api.call = async () => ({ success: true, url: 'https://example.test/login' });
  await ctx.app.openGoogleLogin(true);
  assert.equal(errors.at(-1).id, 'admin-auth-err', 'popup blocker error is visible in active modal');
  assert.equal(ctx.admin._authPending, false);
  console.log('Lounge ranking entry and independent administration passed');
})().catch(e => { console.error(e); process.exitCode = 1; });
